import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../public/', import.meta.url);
const files = [
  ['/', 'index.html', 'text/html; charset=utf-8'],
  ['/styles.css', 'styles.css', 'text/css; charset=utf-8'],
  ['/app.js', 'app.js', 'text/javascript; charset=utf-8'],
  ['/privacy.html', 'privacy.html', 'text/html; charset=utf-8'],
  ['/terms.html', 'terms.html', 'text/html; charset=utf-8'],
  ['/manifest.webmanifest', 'manifest.webmanifest', 'application/manifest+json; charset=utf-8'],
  ['/icon.svg', 'icon.svg', 'image/svg+xml; charset=utf-8']
];

const entries = await Promise.all(files.map(async ([url, file, type]) => [url, {
  body: await readFile(new URL(file, root), 'utf8'),
  type
}]));
const generated = `// Generated by scripts/build-static.mjs. Edit files in public/ instead.\nexport const STATIC_FILES: Record<string, { body: string; type: string }> = ${JSON.stringify(Object.fromEntries(entries))};\n`;
await writeFile(new URL('../src/static-assets.ts', import.meta.url), generated);
